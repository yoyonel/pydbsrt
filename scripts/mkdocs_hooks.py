#!/usr/bin/env python3
"""MkDocs Lifecycle Hooks for pydbsrt Documentation Portal.

Extracts creation and last revision timestamps from Git history and file metadata,
enriches page metadata with temporal tags (for Lunr search indexing), and generates
a docs-dates.json manifest used by the frontend search UI to display dates on matches.
"""

from __future__ import annotations

import json
import re
import subprocess
from datetime import UTC, datetime
from pathlib import Path
from typing import Any, Dict

# Storage & Path Constants
DEFAULT_DOCS_DIR: Path = Path("docs")
DEFAULT_DATES_JS_NAME: str = "docs-dates.js"
FILENAME_DATE_PATTERN: re.Pattern[str] = re.compile(r"^(\d{4}-\d{2}-\d{2})")

# In-memory timestamp cache populated on build start
_DOC_TIMESTAMPS: Dict[str, Dict[str, str]] = {}


def _get_working_tree_modified_docs() -> set[str]:
    """Returns set of docs paths currently modified in Git working tree."""
    try:
        proc = subprocess.run(
            ["git", "status", "--porcelain", "docs/"],
            capture_output=True,
            text=True,
            timeout=3,
            check=False,
        )
        modified = set()
        for line in proc.stdout.splitlines():
            parts = line.strip().split()
            if len(parts) >= 2:
                path_str = parts[-1].strip()
                if path_str.startswith("docs/") and path_str.endswith(".md"):
                    rel = path_str[5:]  # Strip 'docs/'
                    modified.add(rel)
        return modified
    except Exception:
        return set()


def _parse_git_log_output(stdout: str) -> Dict[str, Dict[str, str]]:
    """Extracts creation and last commit date per document from raw git log output."""
    timestamps: Dict[str, Dict[str, str]] = {}
    current_date = ""
    for raw_line in stdout.splitlines():
        line = raw_line.strip()
        if line.startswith("COMMIT:"):
            current_date = line.split(":", 1)[1]
        elif line and current_date and line.startswith("docs/") and line.endswith(".md"):
            rel_path = line[5:]  # Remove 'docs/'
            if rel_path not in timestamps:
                timestamps[rel_path] = {"updated": current_date, "created": current_date}
            else:
                timestamps[rel_path]["created"] = current_date
    return timestamps


def _enrich_file_timestamps(
    timestamps: Dict[str, Dict[str, str]],
    working_modified: set[str],
    today_iso: str,
) -> None:
    """Enriches timestamps with filename dates (YYYY-MM-DD) and working tree modifications."""
    for p in DEFAULT_DOCS_DIR.rglob("*.md"):
        rel = p.relative_to(DEFAULT_DOCS_DIR).as_posix()
        match = FILENAME_DATE_PATTERN.match(p.name)
        if match:
            file_date = match.group(1)
            timestamps.setdefault(rel, {})["created"] = file_date
            timestamps[rel].setdefault("updated", file_date)

        if rel in working_modified:
            timestamps.setdefault(rel, {"created": today_iso})["updated"] = today_iso
        elif rel not in timestamps:
            timestamps[rel] = {"created": today_iso, "updated": today_iso}


def _collect_git_timestamps() -> Dict[str, Dict[str, str]]:
    """Collects creation and last commit date for all docs using git log and filesystem."""
    today_iso = datetime.now(UTC).strftime("%Y-%m-%d")
    working_modified = _get_working_tree_modified_docs()
    try:
        proc = subprocess.run(
            ["git", "log", "--name-only", "--format=COMMIT:%as"],
            capture_output=True,
            text=True,
            timeout=5,
            check=False,
        )
        timestamps = _parse_git_log_output(proc.stdout)
    except Exception:
        timestamps = {}

    _enrich_file_timestamps(timestamps, working_modified, today_iso)
    return timestamps


def _export_manifest(output_dir: Path) -> None:
    """Writes docs-dates.js to the target javascripts directory."""
    legacy_json = output_dir / "assets" / "docs-dates.json"
    if legacy_json.exists():
        legacy_json.unlink()

    js_dir = output_dir / "javascripts"
    js_dir.mkdir(parents=True, exist_ok=True)
    js_path = js_dir / DEFAULT_DATES_JS_NAME

    url_map: Dict[str, Dict[str, str]] = {}
    for rel_path, data in _DOC_TIMESTAMPS.items():
        clean_url = rel_path
        if clean_url.endswith(".md"):
            clean_url = clean_url[:-3]
        if clean_url.endswith("/index") or clean_url == "index":
            clean_url = clean_url[:-5] if clean_url != "index" else ""
        if clean_url and not clean_url.endswith("/"):
            clean_url += "/"
        url_map[clean_url] = data

    js_content = (
        "// Auto-generated by scripts/mkdocs_hooks.py - Do not edit manually\n"
        f"window.__DOCS_DATES__ = {json.dumps(url_map, indent=2, ensure_ascii=False)};\n"
    )
    js_path.write_text(js_content, encoding="utf-8")


def on_pre_build(config: Any) -> None:
    """Pre-build hook: indexes git timestamps and creates initial manifest."""
    global _DOC_TIMESTAMPS
    _DOC_TIMESTAMPS = _collect_git_timestamps()
    _export_manifest(DEFAULT_DOCS_DIR)


def on_page_markdown(markdown: str, page: Any, config: Any, files: Any) -> str:
    """Page markdown hook: injects temporal metadata into page.meta and search text."""
    src_path = getattr(page.file, "src_path", "")
    info = _DOC_TIMESTAMPS.get(src_path)
    if not info:
        return markdown

    created = info.get("created", "")
    updated = info.get("updated", "")

    meta = getattr(page, "meta", None)
    if meta is not None:
        meta["created_date"] = created
        meta["updated_date"] = updated

    # Hidden span with temporal keywords for Lunr search indexing (invisible in UI, zero tag pollution)
    temporal_text = (
        f'\n\n<span class="dbsrt-search-temporal" style="display:none;" aria-hidden="true">'
        f"date: {created} {updated}"
        f"</span>\n"
    )
    return markdown + temporal_text


def on_post_build(config: Any) -> None:
    """Post-build hook: exports manifest docs-dates.json into output site directory."""
    site_dir = Path(config.get("site_dir", "site"))
    _export_manifest(site_dir)
